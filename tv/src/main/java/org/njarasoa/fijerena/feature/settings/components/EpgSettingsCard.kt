/**
 * The guide's device-wide rows in Settings ([extraRows]: Guide auto-refresh, T6). A source's guide
 * sources are reached from that source (Edit Source, the Sources list's Guide), not from here (D6).
 */
@Composable
fun EpgSettingsCard(
    scale: Float,
    extraRows: @Composable () -> Unit,
) {
    GlassPanel(modifier = Modifier.fillMaxWidth().padding(bottom = Spacing.xs.scaled(scale))) {
        Column(modifier = Modifier.padding(Spacing.md.scaled(scale))) {
            Text(
                text = stringResource(R.string.settings_epg_section_title),
                style =
                    MaterialTheme.typography.titleMedium.copy(
                        fontSize =
                            MaterialTheme.typography.titleMedium.fontSize
                                .scaled(scale),
                    ),
                color = CinemaAccent,
            )
            Spacer(modifier = Modifier.height(Spacing.xxs.scaled(scale)))
            extraRows()
        }
    }
}

    @ReadOnlyComposable
    private fun pick(
        filled: ImageVector,
        outlined: ImageVector,
        boldOutlined: ImageVector,
    ): ImageVector =
        when (LocalUiStyle.current.icon.style) {
            IconStyle.FILLED -> filled
            IconStyle.OUTLINED -> outlined
            IconStyle.BOLD_OUTLINED -> boldOutlined
        }

